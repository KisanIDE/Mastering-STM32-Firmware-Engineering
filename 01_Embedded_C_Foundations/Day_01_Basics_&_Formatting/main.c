#include <stdio.h>

int main()
{
    // Print a message with double quotes inside the string
    printf("David says, \"Programming is fun !\"\n");

    // Print terms and conditions message
    printf("**Conditions apply ,\"Offers valid until tomorrow\"\n");

    // Print a Windows file path using escape sequences
    printf("C:\\My computer\\My folder\n");

    // Print another file path
    printf("D:/My documents/My file\n");

    // Print text surrounded by four backslashes on each side
    printf("\\\\\\\\Today is holiday\\\\\\\\\n");

    // Print triple double quotes inside a string
    printf("This is a triple quoted string\"\"\"This month has 30 days\"\"\"\n");

    /*
        Multi-line Comment

        This program demonstrates:
        1. printf() function
        2. Escape sequence \n for new line
        3. Escape sequence \" for double quotes
        4. Escape sequence \\ for backslash
        5. Single-line comments (//)
        6. Multi-line comments 
    */

    return 0;  // End of program
}
